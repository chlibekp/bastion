#!/usr/bin/env python3
"""Generate src/http/known_headers_table.h, the perfect hash of src/http/known_headers.def.

The hash is FNV-1a over the lower-cased bytes, started from a seed. The generator looks for the
smallest power-of-two table (and then the first seed) in which no two known names share a slot,
so a lookup is one hash, one array read and one case-insensitive compare. The output is
committed; run `make gen-known-headers` after editing the .def."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEF = ROOT / "src/http/known_headers.def"
OUT = ROOT / "src/http/known_headers_table.h"
FNV = 16777619
MASK32 = 0xFFFFFFFF


def fnv(name, seed):
    h = seed
    for c in name.encode():
        h = ((h ^ c) * FNV) & MASK32
    return h


def main():
    names = re.findall(r'^X\((\w+),\s*"([^"]+)"\)', DEF.read_text(), re.M)
    if len({n for _, n in names}) != len(names):
        sys.exit("gen-known-headers: duplicate header name in known_headers.def")
    if any(n != n.lower() for _, n in names):
        sys.exit("gen-known-headers: names must be lower case")
    if len(names) > 254:
        sys.exit("gen-known-headers: ids are one byte in the table: at most 254 headers")
    size = 1
    while size < 2 * len(names):
        size *= 2
    while size <= 4096:
        for seed in range(1, 200000):
            slots = {}
            for i, (_, n) in enumerate(names, 1):
                slots.setdefault(fnv(n, seed) & (size - 1), []).append(i)
            if all(len(v) == 1 for v in slots.values()):
                emit(size, seed, {k: v[0] for k, v in slots.items()})
                return
        size *= 2
    sys.exit("gen-known-headers: no perfect hash found")


def emit(size, seed, slots):
    rows = []
    for i in range(0, size, 16):
        rows.append("\t" + ", ".join(str(slots.get(j, 0)) for j in range(i, min(i + 16, size))) + ",")
    OUT.write_text(
        "/* Generated by scripts/gen-known-headers.py from known_headers.def: do not edit. */\n"
        f"#define BST_HDR_HASH_SEED {seed}u\n"
        f"#define BST_HDR_HASH_MASK {size - 1}u\n"
        f"static const unsigned char bst_hdr_slots[{size}] = {{\n" + "\n".join(rows) + "\n};\n")
    print(f"gen-known-headers: {size} slots, seed {seed}")


main()
