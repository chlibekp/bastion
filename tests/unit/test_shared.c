TEST(siphash_vectors)
{
	uint8_t key[16], in[64];
	for (int i = 0; i < 16; i++)
		key[i] = (uint8_t)i;
	for (int i = 0; i < 64; i++)
		in[i] = (uint8_t)i;
	for (size_t len = 0; len < 64; len++) {
		uint64_t h = bst_siphash13(key, in, len);
		uint8_t le[8];
		for (int j = 0; j < 8; j++)
			le[j] = (uint8_t)(h >> (8 * j));
		if (memcmp(le, sip13_vectors[len], 8) != 0)
			TAP_FAIL_("vector mismatch at len %zu", len);
	}
}

#define CAP 256u

static bst_spsc *new_ring(void **mem_out, size_t cap)
{
	void *mem = aligned_alloc(64, BST_SPSC_BYTES(cap));
	*mem_out = mem;
	return mem ? bst_spsc_init(mem, cap) : NULL;
}

TEST(ring_wraparound)
{
	void *mem;
	bst_spsc *r = new_ring(&mem, CAP);
	ASSERT(r != NULL);
	uint8_t in[100], out[100];
	/* Sizes chosen so records straddle the end of the buffer many times. */
	for (unsigned n = 0; n < 500; n++) {
		uint32_t len = (n * 37u) % 91u;
		for (uint32_t i = 0; i < len; i++)
			in[i] = (uint8_t)(n + i);
		ASSERT(bst_spsc_push(r, in, len));
		ASSERT_EQ(bst_spsc_pop(r, out, sizeof out), (int32_t)len);
		ASSERT(memcmp(in, out, len) == 0);
	}
	/* Two in flight so the wrap offset keeps moving. */
	for (unsigned n = 0; n < 300; n++) {
		uint8_t a[50], b[61];
		memset(a, (int)n, sizeof a);
		memset(b, (int)n + 1, sizeof b);
		ASSERT(bst_spsc_push(r, a, sizeof a));
		ASSERT(bst_spsc_push(r, b, sizeof b));
		ASSERT_EQ(bst_spsc_pop(r, out, sizeof out), 50);
		ASSERT(memcmp(a, out, 50) == 0);
		ASSERT_EQ(bst_spsc_pop(r, out, sizeof out), 61);
		ASSERT(memcmp(b, out, 61) == 0);
	}
	ASSERT_EQ(bst_spsc_pop(r, out, sizeof out), BST_SPSC_EMPTY);
	bst_spsc_free(r);
	free(mem);
}

TEST(ring_full)
{
	void *mem;
	bst_spsc *r = new_ring(&mem, CAP);
	ASSERT(r != NULL);
	uint8_t msg[60], out[64];
	memset(msg, 0xab, sizeof msg);
	int pushed = 0;
	while (bst_spsc_push(r, msg, sizeof msg))
		pushed++;
	ASSERT_EQ(pushed, (int)(CAP / (sizeof msg + 4)));
	ASSERT(!bst_spsc_push(r, msg, sizeof msg));
	for (int i = 0; i < pushed; i++) {
		ASSERT_EQ(bst_spsc_pop(r, out, sizeof out), (int32_t)sizeof msg);
		ASSERT(memcmp(out, msg, sizeof msg) == 0);
	}
	ASSERT_EQ(bst_spsc_pop(r, out, sizeof out), BST_SPSC_EMPTY);
	ASSERT(bst_spsc_push(r, msg, sizeof msg));
	bst_spsc_free(r);
	free(mem);
}

TEST(ring_oversize_push)
{
	void *mem;
	bst_spsc *r = new_ring(&mem, CAP);
	ASSERT(r != NULL);
	uint8_t big[CAP + 8] = {0};
	ASSERT(!bst_spsc_push(r, big, CAP - 3)); /* 4 + len > cap */
	ASSERT(!bst_spsc_push(r, big, CAP));
	ASSERT(!bst_spsc_push(r, big, UINT32_MAX));
	ASSERT(bst_spsc_push(r, big, CAP - 4)); /* exactly fills */
	uint8_t out[CAP];
	ASSERT_EQ(bst_spsc_pop(r, out, sizeof out), CAP - 4);
	/* A reader buffer that is too small does not consume the record. */
	ASSERT(bst_spsc_push(r, big, 20));
	ASSERT_EQ(bst_spsc_pop(r, out, 10), BST_SPSC_SMALL);
	ASSERT_EQ(bst_spsc_pop(r, out, 20), 20);
	bst_spsc_free(r);
	free(mem);
}

